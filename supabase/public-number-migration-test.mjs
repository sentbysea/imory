const MIGRATION_FILE = readFileSync(MIGRATION_PATH, "utf8");

/*
  파일의 rollback 은 주석 블록 안에 있다(다른 migration 과 같은 형식).
  9) 절에서 **실제로 실행해** 되돌아가는지 보려면 주석을 벗겨야 한다.
  줄머리의 "--   " 를 걷어내고 begin~commit 사이만 취한다.
*/

function extractRollbackSql(text) {

  const marker = text.indexOf("-- ROLLBACK");

  const tail = marker < 0 ? "" : text.slice(marker);

  const lines = tail
    .split("\n")
    .filter(line => /^--\s{3}\S/.test(line) || /^--\s{3}$/.test(line))
    .map(line => line.replace(/^--\s{3}/, ""));

  return lines.join("\n");

}

const ROLLBACK = extractRollbackSql(MIGRATION_FILE);

let passed = 0;
const failures = [];

function check(name, condition, detail) {
  if (condition) { passed += 1; console.log(`  ok   ${name}`); }
  else { failures.push(`${name}${detail ? " — " + detail : ""}`); console.log(`  FAIL ${name}${detail ? " — " + detail : ""}`); }
}


/* =========================================================
   이 migration 직전까지의 상태

   categories / posts 는 2026-09-15 프로덕션 PostgREST 로 실측한
   컬럼 구성을 옮겨 적은 것이다(다른 migration 검증과 같은 방식).
   이 migration 은 두 테이블에 컬럼만 더하므로, 번호 발급과 무관한
   컬럼은 전부 적지 않는다.
========================================================== */

const BASELINE = `
create schema if not exists auth;

create role anon;
create role authenticated;

create table auth.users (
  id uuid primary key
);

create table public.categories (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  slug text,
  sort_order integer,
  type text not null default 'post',
  created_at timestamptz not null default now()
);

create table public.posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  category_id bigint references public.categories(id) on delete set null,
  title text,
  visibility text not null default 'public',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

/*
  posts 는 프로덕션에서 컬럼 단위 GRANT 다(select=* 가 42501).
  새 컬럼에 GRANT 가 실제로 붙는지 보려면 그 상태를 흉내 내야 한다.
  categories 는 테이블 단위 GRANT 다.
*/
grant select (id, user_id, category_id, title, visibility, created_at, updated_at)
  on public.posts to anon, authenticated;

grant select on public.categories to anon, authenticated;
`;

const A = "11111111-2222-3333-4444-555555555555";
const B = "99999999-8888-7777-6666-555555555555";


async function seed(db) {

  await db.exec(BASELINE);

  await db.exec(`insert into auth.users (id) values ('${A}'), ('${B}');`);

  /*
    일부러 id 를 섞어 넣는다 — 사용자 A 의 첫 카테고리가 id 7,
    사용자 B 의 첫 카테고리가 id 3 이다. 공개 번호는 둘 다 1 이
    나와야 한다(= id 순서가 아니라 사용자 안의 순서).
  */

  await db.exec(`
    insert into public.categories (id, user_id, name, created_at)
    values
      (7,  '${A}', 'A-첫번째', '2026-01-01T00:00:00Z'),
      (12, '${A}', 'A-두번째', '2026-02-01T00:00:00Z'),
      (3,  '${B}', 'B-첫번째', '2026-01-05T00:00:00Z'),
      (9,  '${B}', 'B-두번째', '2026-03-01T00:00:00Z');
  `);

  /*
    created_at 이 같은 두 글(31, 30)을 넣어 tie-break(id 오름차순)를
    실제로 태운다.
  */

  await db.exec(`
    insert into public.posts (id, user_id, category_id, title, created_at)
    values
      (38, '${A}', 7,  'A-글1', '2026-01-01T00:00:00Z'),
      (31, '${A}', 7,  'A-글3', '2026-03-01T00:00:00Z'),
      (30, '${A}', 12, 'A-글2', '2026-03-01T00:00:00Z'),
      (5,  '${B}', 3,  'B-글1', '2026-01-02T00:00:00Z'),
      (6,  '${B}', 3,  'B-글2', '2026-02-02T00:00:00Z');
  `);

  /*
    id 를 명시해서 넣었으므로(generated BY DEFAULT) identity
    시퀀스는 아직 1 에 머물러 있다. 아래 절에서 id 없이 넣는
    INSERT 가 PK 와 부딪히지 않도록 여기서 한 번 올려 둔다 —
    프로덕션에는 없는, 이 fixture 때문에 생기는 일이다.
  */

  await db.exec(`
    alter table public.categories alter column id restart with 1000;
    alter table public.posts alter column id restart with 1000;
  `);

}


async function noOf(db, table, id) {
  const r = await db.query(
    `select public_no from public.${table} where id = $1`, [id]
  );
  return r.rows[0] ? Number(r.rows[0].public_no) : undefined;
}

async function counterOf(db, userId, resource) {
  const r = await db.query(
    "select last_no from public.public_no_counters where user_id = $1 and resource = $2",
    [userId, resource]
  );
  return r.rows[0] ? Number(r.rows[0].last_no) : undefined;
}


async function run() {

  const db = new PGlite();

  await seed(db);

  /* migration 전의 id 를 그대로 기억해 둔다(7 절에서 비교) */

  const idsBefore = (await db.query(
    "select id from public.posts order by id"
  )).rows.map(r => Number(r.id)).join(",");

  await db.exec(MIGRATION_FILE);


  /* =========================================================
     1) backfill
  ========================================================== */

  console.log("\n[backfill] 사용자별로 1 부터");

  check(
    "★ 사용자 A 의 첫 카테고리(id 7)가 공개 번호 1 이다",
    await noOf(db, "categories", 7) === 1,
    String(await noOf(db, "categories", 7))
  );

  check(
    "사용자 A 의 두 번째 카테고리(id 12)가 2 다",
    await noOf(db, "categories", 12) === 2
  );

  check(
    "★ 사용자 B 도 1 부터 다시 센다(id 3 -> 1, id 9 -> 2)",
    await noOf(db, "categories", 3) === 1 &&
    await noOf(db, "categories", 9) === 2,
    `${await noOf(db, "categories", 3)} / ${await noOf(db, "categories", 9)}`
  );

  check(
    "★ 사용자 A 의 첫 글(id 38)이 공개 번호 1 이다",
    await noOf(db, "posts", 38) === 1,
    String(await noOf(db, "posts", 38))
  );

  check(
    "created_at 동률은 id 오름차순으로 갈린다(30 -> 2, 31 -> 3)",
    await noOf(db, "posts", 30) === 2 &&
    await noOf(db, "posts", 31) === 3,
    `${await noOf(db, "posts", 30)} / ${await noOf(db, "posts", 31)}`
  );

  check(
    "★ 사용자 B 의 글도 1 부터다(id 5 -> 1, id 6 -> 2)",
    await noOf(db, "posts", 5) === 1 &&
    await noOf(db, "posts", 6) === 2
  );

  check(
    "사용자별 번호가 빈 곳 없이 이어진다",
    await (async () => {
      const r = await db.query(`
        select user_id,
               count(*)          as n,
               min(public_no)    as lo,
               max(public_no)    as hi,
               count(distinct public_no) as d
          from public.posts group by user_id
      `);
      return r.rows.every(row =>
        Number(row.lo) === 1 &&
        Number(row.hi) === Number(row.n) &&
        Number(row.d) === Number(row.n)
      );
    })()
  );

  check(
    "카운터가 backfill 최댓값으로 맞춰진다",
    await counterOf(db, A, "post") === 3 &&
    await counterOf(db, A, "category") === 2 &&
    await counterOf(db, B, "post") === 2,
    `${await counterOf(db, A, "post")} / ${await counterOf(db, A, "category")} / ${await counterOf(db, B, "post")}`
  );

  await db.exec(MIGRATION_FILE);

  check(
    "★ migration 을 다시 실행해도 이미 붙은 번호가 달라지지 않는다",
    await noOf(db, "posts", 38) === 1 &&
    await noOf(db, "posts", 31) === 3 &&
    await counterOf(db, A, "post") === 3
  );


  /* =========================================================
     2) assign
  ========================================================== */

  console.log("\n[assign] 새 행의 번호");

  await db.exec(`
    insert into public.posts (user_id, category_id, title)
    values ('${A}', 7, 'A-새글');
  `);

  const newA = (await db.query(
    "select id, public_no from public.posts where title = 'A-새글'"
  )).rows[0];

  check(
    "새 글은 그 블로그의 다음 번호를 받는다(3 다음은 4)",
    Number(newA.public_no) === 4,
    String(newA.public_no)
  );

  await db.exec(`
    insert into public.posts (user_id, category_id, title, public_no)
    values ('${A}', 7, 'A-값들고온글', 999);
  `);

  check(
    "★ 클라이언트가 보낸 public_no 는 버려지고 다시 발급된다",
    Number((await db.query(
      "select public_no from public.posts where title = 'A-값들고온글'"
    )).rows[0].public_no) === 5
  );

  await db.exec(`
    insert into public.categories (user_id, name) values ('${B}', 'B-세번째');
  `);

  check(
    "카테고리 카운터는 글 카운터와 따로 논다",
    Number((await db.query(
      "select public_no from public.categories where name = 'B-세번째'"
    )).rows[0].public_no) === 3
  );

  await db.exec(`
    insert into auth.users (id) values ('33333333-3333-3333-3333-333333333333');
    insert into public.categories (user_id, name)
    values ('33333333-3333-3333-3333-333333333333', '새 사용자 첫 카테고리');
    insert into public.posts (user_id, title)
    values ('33333333-3333-3333-3333-333333333333', '새 사용자 첫 글');
  `);

  check(
    "★ 새로 가입한 사용자의 첫 카테고리·첫 글이 둘 다 1 이다",
    Number((await db.query(
      "select public_no from public.categories where name = '새 사용자 첫 카테고리'"
    )).rows[0].public_no) === 1 &&
    Number((await db.query(
      "select public_no from public.posts where title = '새 사용자 첫 글'"
    )).rows[0].public_no) === 1
  );


  /* =========================================================
     3) frozen — 재사용 금지
  ========================================================== */

  console.log("\n[frozen] 지운 번호를 다시 쓰지 않는다");

  await db.exec("delete from public.posts where title = 'A-값들고온글';");

  await db.exec(`
    insert into public.posts (user_id, category_id, title)
    values ('${A}', 7, 'A-지운다음글');
  `);

  check(
    "★ 맨 끝 번호(5)를 지워도 다음 글은 6 을 받는다",
    Number((await db.query(
      "select public_no from public.posts where title = 'A-지운다음글'"
    )).rows[0].public_no) === 6
  );

  await db.exec("delete from public.posts where id = 38;");

  check(
    "★ 앞 번호를 지워도 뒤 번호가 당겨지지 않는다",
    await noOf(db, "posts", 30) === 2 &&
    await noOf(db, "posts", 31) === 3
  );


  /* =========================================================
     4) immutable
  ========================================================== */

  console.log("\n[immutable] 한 번 붙은 번호는 바뀌지 않는다");

  await db.exec("update public.posts set public_no = 777 where id = 31;");

  check(
    "★ UPDATE 로 public_no 를 바꿀 수 없다",
    await noOf(db, "posts", 31) === 3,
    String(await noOf(db, "posts", 31))
  );

  await db.exec("update public.posts set title = '제목만 고침' where id = 31;");

  check(
    "다른 컬럼만 고치면 번호는 그대로다",
    await noOf(db, "posts", 31) === 3
  );

  await db.exec("update public.posts set category_id = 12 where id = 31;");

  check(
    "★ 카테고리를 옮겨도 공개 주소는 그대로다(번호 불변)",
    await noOf(db, "posts", 31) === 3
  );


  /* =========================================================
     5) unique / not null
  ========================================================== */

  console.log("\n[unique] (user_id, public_no)");

  check(
    "★ 두 블로그가 같은 번호 1 을 동시에 가진다",
    await (async () => {
      const r = await db.query(
        "select count(*)::int as n from public.posts where public_no = 1"
      );
      return r.rows[0].n >= 2;
    })()
  );

  /*
    평소에는 트리거가 값을 되돌려 버려서 겹칠 기회 자체가 없다.
    그래서 트리거를 잠시 끄고 **인덱스만** 남긴 상태로 시험한다 —
    발급 경로가 뚫려도 DB 가 막는다는 것이 이 인덱스의 존재
    이유다.
  */

  check(
    "★ 발급 경로를 우회해도 같은 블로그 안의 번호 중복은 DB 가 막는다",
    await (async () => {
      await db.exec(`
        insert into public.posts (id, user_id, category_id, title)
        values (900, '${A}', 7, '겹침');
      `);
      try {
        await db.exec(`
          alter table public.posts disable trigger posts_assign_public_no_trg;
          update public.posts set public_no = 3 where id = 900;
        `);
        return false;
      } catch (err) {
        return err.code === "23505";
      } finally {
        await db.exec(
          "alter table public.posts enable trigger posts_assign_public_no_trg;"
        );
      }
    })()
  );

  check(
    "public_no 는 NOT NULL 이다",
    await (async () => {
      const r = await db.query(`
        select is_nullable from information_schema.columns
         where table_schema='public' and table_name='posts' and column_name='public_no'
      `);
      return r.rows[0].is_nullable === "NO";
    })()
  );

  check(
    "unique 인덱스가 두 테이블에 다 있다",
    await (async () => {
      const r = await db.query(`
        select indexname from pg_indexes
         where schemaname='public'
           and indexname in ('posts_user_public_no_key','categories_user_public_no_key')
      `);
      return r.rows.length === 2;
    })()
  );


  /* =========================================================
     6) concurrent
  ========================================================== */

  console.log("\n[concurrent] 동시에 여러 글을 만들어도 겹치지 않는다");

  await db.exec(`
    insert into public.posts (user_id, category_id, title)
    select '${A}', 7, '무더기-' || g from generate_series(1, 50) g;
  `);

  check(
    "★ 한 문장으로 50 개를 넣어도 번호가 전부 다르다",
    await (async () => {
      const r = await db.query(`
        select count(*)::int as n, count(distinct public_no)::int as d
          from public.posts where user_id = '${A}'
      `);
      return r.rows[0].n === r.rows[0].d;
    })()
  );

  check(
    "★ 카운터가 실제 최댓값과 정확히 같다(건너뛴 번호 없음)",
    await (async () => {
      const r = await db.query(
        `select max(public_no) as m from public.posts where user_id = '${A}'`
      );
      return Number(r.rows[0].m) === await counterOf(db, A, "post");
    })(),
    `counter=${await counterOf(db, A, "post")}`
  );

  /*
    PGlite 는 한 프로세스 안의 단일 연결이라 진짜 병렬 트랜잭션을
    만들 수 없다. 대신 발급 문장이 **잠금을 잡는 형태인지**를
    본다 — insert ... on conflict do update 는 충돌한 행에 배타
    잠금을 잡고, 그래서 두 번째 세션이 기다렸다가 갱신된 값을
    읽는다. 아래는 그 문장이 실제로 그 자리에서 +1 한 값을
    돌려주는지(= 읽고-쓰기가 한 문장인지) 확인한다.
  */

  check(
    "★ 발급이 read-then-write 두 문장이 아니라 한 문장이다",
    await (async () => {
      const src = (await db.query(`
        select prosrc from pg_proc
         where proname = 'assign_public_no'
      `)).rows[0].prosrc;
      return (
        /on conflict\s*\(user_id, resource\)\s*do update/.test(src) &&
        /returning\s+c\.last_no\s+into/.test(src) &&
        !/select\s+coalesce\s*\(\s*max\s*\(/i.test(src)
      );
    })()
  );


  /* =========================================================
     7) PK 불변
  ========================================================== */

  console.log("\n[pk] 내부 id 는 하나도 바뀌지 않았다");

  check(
    "★ migration 전에 있던 글의 id 가 그대로다",
    await (async () => {
      const now = (await db.query(`
        select id from public.posts where id in (30, 31, 5, 6) order by id
      `)).rows.map(r => Number(r.id)).join(",");
      return now === "5,6,30,31" && idsBefore.includes("38");
    })()
  );

  check(
    "★ posts.category_id 는 여전히 categories.id 를 가리킨다",
    await (async () => {
      const r = await db.query(`
        select p.id from public.posts p
          join public.categories c on c.id = p.category_id
         where p.id = 31 and c.id = 12
      `);
      return r.rows.length === 1;
    })()
  );


  /* =========================================================
     8) GRANT / RLS
  ========================================================== */

  console.log("\n[grant] 권한");

  check(
    "★ posts.public_no 는 anon/authenticated 에 SELECT 만 열린다",
    await (async () => {
      const r = await db.query(`
        select grantee, privilege_type from information_schema.column_privileges
         where table_schema='public' and table_name='posts'
           and column_name='public_no' and grantee in ('anon','authenticated')
      `);
      const kinds = new Set(r.rows.map(x => x.privilege_type));
      const who = new Set(r.rows.map(x => x.grantee));
      return kinds.size === 1 && kinds.has("SELECT") && who.size === 2;
    })()
  );

  check(
    "categories 는 테이블 단위 GRANT 라 새 컬럼이 자동으로 읽힌다",
    await (async () => {
      const r = await db.query(`
        select has_column_privilege('anon', 'public.categories', 'public_no', 'SELECT') as ok
      `);
      return r.rows[0].ok === true;
    })()
  );

  check(
    "★ 카운터 테이블에는 anon/authenticated 권한이 전혀 없다",
    await (async () => {
      const r = await db.query(`
        select grantee from information_schema.table_privileges
         where table_schema='public' and table_name='public_no_counters'
           and grantee in ('anon','authenticated')
      `);
      return r.rows.length === 0;
    })()
  );

  check(
    "카운터 테이블에 RLS 가 켜져 있고 정책이 하나도 없다",
    await (async () => {
      const rls = await db.query(`
        select relrowsecurity from pg_class
         where oid = 'public.public_no_counters'::regclass
      `);
      const pol = await db.query(`
        select policyname from pg_policies
         where schemaname='public' and tablename='public_no_counters'
      `);
      return rls.rows[0].relrowsecurity === true && pol.rows.length === 0;
    })()
  );

  check(
    "발급 함수는 SECURITY DEFINER 이고 search_path 가 고정돼 있다",
    await (async () => {
      const r = await db.query(`
        select prosecdef, proconfig from pg_proc where proname='assign_public_no'
      `);
      return r.rows[0].prosecdef === true &&
        (r.rows[0].proconfig || []).some(c => c.startsWith("search_path="));
    })(),
    JSON.stringify((await db.query(
      "select proconfig from pg_proc where proname='assign_public_no'"
    )).rows[0])
  );


  /* =========================================================
     9) rollback
  ========================================================== */

  console.log("\n[rollback] 파일의 rollback 블록을 실제로 실행한다");

  check(
    "rollback 블록을 파일에서 읽어냈다",
    /drop\s+table\s+if\s+exists\s+public\.public_no_counters/.test(ROLLBACK),
    ROLLBACK.slice(0, 60)
  );

  await db.exec(ROLLBACK);

  check(
    "★ 되돌리면 컬럼·트리거·함수·카운터 테이블이 전부 사라진다",
    await (async () => {
      const cols = await db.query(`
        select 1 from information_schema.columns
         where table_schema='public' and column_name='public_no'
      `);
      const fn = await db.query(
        "select 1 from pg_proc where proname='assign_public_no'"
      );
      const tbl = await db.query(`
        select 1 from information_schema.tables
         where table_schema='public' and table_name='public_no_counters'
      `);
      return cols.rows.length === 0 && fn.rows.length === 0 && tbl.rows.length === 0;
    })()
  );

  check(
    "★ 되돌려도 글 자체는 그대로 남는다(id 보존)",
    await (async () => {
      const r = await db.query(
        "select id from public.posts where id in (30, 31) order by id"
      );
      return r.rows.map(x => Number(x.id)).join(",") === "30,31";
    })()
  );

  await db.exec(MIGRATION_FILE);

  check(
    "★ 되돌린 뒤 다시 적용해도 같은 규칙으로 번호가 다시 붙는다",
    await noOf(db, "posts", 30) === 1 &&
    await noOf(db, "categories", 7) === 1,
    `${await noOf(db, "posts", 30)} / ${await noOf(db, "categories", 7)}`
  );

  await db.close();

}


