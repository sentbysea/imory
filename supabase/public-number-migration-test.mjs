/* =========================================================
   PUBLIC-NUMBER-1 공개 URL 번호 migration 검증 (PGlite — 실제 Postgres)

   기준 문서: IMORY_PUBLIC_NUMBER_DESIGN.md
   대상:      supabase/migrations/20260915100000_public_numbers_for_categories_and_posts.sql

   무엇을 확인하는가
   ----------------
   1) [backfill]  사용자별로 created_at 오름차순(동률은 id)으로 1 부터.
                  블로그마다 독립적으로 1 부터 다시 센다.
                  재실행해도 값이 달라지지 않는다.
   2) [assign]    새 행은 카운터에서 다음 번호를 받는다. 클라이언트가
                  들고 온 값은 버려진다.
   3) [frozen]    ★ 맨 끝 번호를 지워도 다음 행이 그 번호를 **재사용하지
                  않는다**. 앞 번호를 지워도 뒤 번호가 당겨지지 않는다.
   4) [immutable] UPDATE 로 public_no 를 바꿀 수 없다.
   5) [unique]    (user_id, public_no) 가 UNIQUE 이고 NOT NULL 이다.
                  같은 번호를 두 블로그가 가져도 충돌하지 않는다.
   6) [concurrent] ★ 같은 블로그에 여러 글을 한꺼번에 넣어도 번호가
                  겹치지 않는다(단일 문장 다중 INSERT + 병렬 세션).
   7) [pk]        id / sequence 는 하나도 바뀌지 않았다.
   8) [grant]     posts.public_no 는 SELECT 만, 카운터 테이블은
                  anon/authenticated 에 아무 권한도 없고 RLS 가 켜져 있다.
   9) [rollback]  파일 안의 rollback 블록을 실제로 실행해 원상복구되는지.

   실행:
     node supabase/public-number-migration-test.mjs

   PGlite 는 supabase/.temp/gallery-validation/node_modules 에 이미
   설치돼 있다(다른 migration 검증 때 받은 것). 이 저장소에는 패키지
   매니저가 없으므로 새로 설치하지 않고 그 경로에서 import 한다.
========================================================== */

