-- =========================================================
-- HIGHLIGHT-1 후속 — posts.updated_at 읽기 권한 한 칸
--
-- 기준 문서: IMORY_HIGHLIGHT1_DESIGN.md §6 / §11-1
--
-- 이 migration이 하는 일은 **딱 하나**다:
--   public.posts 의 SELECT 허용 컬럼 목록에 updated_at 을 더한다.
--
-- 왜 필요한가
-- -----------
-- 메모 카드의 "원문에서 위치를 찾을 수 없음"은 마지막으로 그 글을
-- 열었을 때의 판정 결과이고, 그 기록은 이 브라우저에 남는다
-- (posts/view/posts-view-highlight-store.js).
--
-- 그런데 그 사이에 원문을 고치면 예전 판정은 **이전 본문에 대한
-- 결과**다. 그것을 현재 상태인 것처럼 남겨 두면 "고쳤는데 아직도
-- 못 찾았다고 나온다" 또는 그 반대가 된다. 그래서 기록에 확인 당시의
-- 글 수정 시각을 함께 적고, 지금 값과 다르면 "아직 확인하지 않음"으로
-- 되돌린다 — 그 비교에 필요한 값이 posts.updated_at 하나다.
--
-- 카드 목록 쿼리가 이미 posts 를 embed 하고 있으므로 컬럼 하나가
-- 같은 응답에 함께 실려 온다. 카드마다 원문을 다시 받아 판정하는
-- 방식(요청이 카드 수만큼 늘어난다)은 쓰지 않는다.
--
-- 왜 안전한가
-- -----------
-- updated_at 은 "이 글이 마지막으로 수정된 시각"이고, 그 글이 이미
-- 보이는 사람에게만 간다 — RLS 는 그대로다. 이 컬럼 하나로 새로
-- 드러나는 것은 공개된 글의 수정 시각뿐이고, 비공개/비밀글은 애초에
-- 행 자체가 오지 않는다. secret_password_hash 는 여기서도 목록에
-- 없다(20260902110000 의 원칙 그대로 — column-level GRANT 가 유일한
-- 차단 수단이다).
--
-- 기존 컬럼 목록은 한 글자도 바꾸지 않는다. GRANT 는 누적이므로
-- 이 한 줄이 예전 GRANT 를 대체하지 않고 더하기만 한다.
--
-- 실행 순서
-- ---------
-- 20260913100000_post_highlights_and_memo_folders.sql 다음에 적용한다
-- (순서가 바뀌어도 결과는 같지만, 파일 이름 순서대로 두는 편이
--  나중에 읽기 쉽다). 그대로 다시 실행해도 안전하다.
--
-- ※ Supabase SQL Editor 에 붙여넣어 적용한다. supabase CLI 로
--   적용하게 되면 CLI 가 이미 트랜잭션을 열므로 begin/commit 두
--   줄은 제거한다.
-- =========================================================

begin;


grant select (updated_at) on public.posts to anon, authenticated;


comment on column public.posts.updated_at is
  '글이 마지막으로 저장된 시각. HIGHLIGHT-1 후속부터 SELECT 가 열려 있다 — 메모 카드의 "원문 위치 확인" 기록이 아직 유효한지(그 뒤에 본문이 바뀌지 않았는지) 판정하는 유일한 근거이고, 그 판정을 위해 카드마다 원문을 다시 받지 않기 위해서다. RLS 는 그대로이므로 이 값도 그 글이 이미 보이는 사람에게만 간다.';


commit;
