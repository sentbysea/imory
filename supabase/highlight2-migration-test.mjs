/* =========================================================
   5) [contract] 프런트 공용 상수 == DB predicate

   UI 상수와 DB 제약이 서로 다른 타입 목록을 쓰지 않게(요구사항 6)
   두 파일의 글자를 직접 비교한다. DB 는 신뢰 경계라 목록을 가져올
   수 없으니, 대신 "어긋나면 테스트가 깨진다"를 만든다.
========================================================== */

console.log("\n[contract]");

{
  const constants = readFileSync(join(REPO, "core", "lib", "category-types.js"), "utf8");

  const listOf = (name) => {
    const m = constants.match(new RegExp("const\\s+" + name + "\\s*=\\s*\\[([^\\]]*)\\]"));
    return m ? m[1].split(",").map(v => v.trim().replace(/^["']|["']$/g, "")).filter(Boolean) : null;
  };

  const frontAll = listOf("CATEGORY_TYPES");
  const frontSingleton = listOf("SINGLETON_CATEGORY_TYPES");

  /* DB: partial unique index 의 predicate 에 적힌 타입 */
  const predicate = MIGRATION.match(/where type in \(([^)]*)\)/);
  const dbSingleton = predicate
    ? predicate[1].split(",").map(v => v.trim().replace(/^'|'$/g, ""))
    : null;

  check("[contract] singleton 목록이 프런트와 DB 에서 같다",
    Boolean(frontSingleton && dbSingleton) &&
    frontSingleton.slice().sort().join(",") === dbSingleton.slice().sort().join(","),
    JSON.stringify({ front: frontSingleton, db: dbSingleton }));

  check("[contract] 프런트 타입 목록이 post/gallery/banner/highlight 네 개다",
    Boolean(frontAll) && frontAll.join(",") === "post,gallery,banner,highlight",
    JSON.stringify(frontAll));

  check("[contract] 프런트 목록에 memo / guest 가 없다",
    Boolean(frontAll) && !frontAll.includes("memo") && !frontAll.includes("guest"));

  /* 주석(-- 줄, 블록 주석)을 걷어낸 실행문만 본다 */
  const sqlOnly = MIGRATION
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .split("\n")
    .filter(line => !/^\s*--/.test(line))
    .join("\n");

  check("[contract] migration 실행문이 memo / guest 타입을 허용하지 않는다",
    !/'memo'/.test(sqlOnly) && !/'guest'/.test(sqlOnly),
    sqlOnly.split("\n").filter(l => /'memo'|'guest'/.test(l)).join(" | "));
}


