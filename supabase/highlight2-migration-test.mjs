const BASELINE = `
create schema if not exists auth;

create table auth.users (
  id uuid primary key
);

create table auth.imory_session (
  uid uuid
);
insert into auth.imory_session values (null);

create or replace function auth.uid() returns uuid
language sql stable as $$ select uid from auth.imory_session limit 1 $$;

create table public.categories (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  slug text,
  sort_order integer,
  created_at timestamptz not null default now(),
  type text not null default 'post',
  list_style text not null default 'list',
  page_size smallint not null default 12,
  secret_cover_mode text not null default 'lock',
  secret_cover_path text,
  constraint categories_type_check check (type in ('post', 'gallery', 'banner')),
  constraint categories_list_style_check check (list_style in ('list', 'gallery')),
  constraint categories_page_size_check check (page_size in (6, 12, 18, 24)),
  constraint categories_secret_cover_mode_check check (secret_cover_mode in ('lock', 'image'))
);

create table public.posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  category_id bigint references public.categories(id) on delete set null,
  folder_id bigint,
  title text,
  visibility text not null default 'public',
  sort_order integer,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.post_folders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  category_id bigint not null references public.categories(id) on delete cascade,
  parent_id bigint references public.post_folders(id) on delete restrict,
  name text not null,
  depth smallint not null default 1,
  sort_order integer not null default 0
);

create table public.banners (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.categories(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text,
  url text,
  image_url text,
  image_path text,
  sort_order integer,
  created_at timestamptz not null default now()
);

create table public.post_highlights (
  id uuid primary key default gen_random_uuid(),
  post_id bigint not null references public.posts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  color text not null,
  excerpt text not null,
  prefix text not null default '',
  suffix text not null default '',
  text_start integer not null,
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.memo_folder_settings (
  category_id bigint primary key references public.categories(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  sort_order integer not null default 0,
  cover_path text,
  has_cover boolean generated always as (cover_path is not null) stored,
  cover_ratio text not null default 'original' check (cover_ratio in ('1:1','3:4','4:3','original')),
  cover_focus_x smallint not null default 50,
  cover_focus_y smallint not null default 50,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index memo_folder_settings_user_idx on public.memo_folder_settings(user_id, sort_order);
alter table public.memo_folder_settings enable row level security;
create policy memo_folder_settings_public_read on public.memo_folder_settings for select using (true);

create or replace function public.upsert_own_memo_folder_settings(
  p_category_id bigint, p_sort_order integer, p_cover_ratio text,
  p_cover_focus_x smallint, p_cover_focus_y smallint,
  p_cover_path text default null, p_keep_cover boolean default false
) returns text language plpgsql security definer set search_path = '' as $fn$
declare v_previous text;
begin
  select s.cover_path into v_previous from public.memo_folder_settings s where s.category_id = p_category_id;
  insert into public.memo_folder_settings(category_id, user_id, sort_order, cover_path, cover_ratio, cover_focus_x, cover_focus_y)
  values (p_category_id, auth.uid(), coalesce(p_sort_order,0), p_cover_path, coalesce(p_cover_ratio,'original'),
          coalesce(p_cover_focus_x,50), coalesce(p_cover_focus_y,50))
  on conflict (category_id) do update set sort_order = excluded.sort_order;
  return v_previous;
end; $fn$;

create or replace function public.get_own_highlight_folder_cover_paths(p_category_ids bigint[])
returns setof text language sql stable security definer set search_path = '' as $fn$
  select s.cover_path from public.memo_folder_settings s
   where s.user_id = auth.uid() and s.category_id = any(p_category_ids) and s.cover_path is not null
$fn$;

create or replace function public.get_highlight_folder_cover_object(p_category_id bigint)
returns table(storage_path text, mime_type text) language sql stable security definer set search_path = '' as $fn$
  select s.cover_path, null::text from public.memo_folder_settings s
   where s.category_id = p_category_id and s.cover_path is not null
$fn$;

create role anon;
create role authenticated;
`;

const USER_A = "11111111-1111-4111-8111-111111111111";
const USER_B = "22222222-2222-4222-8222-222222222222";

async function freshDb(seed) {
  const db = new PGlite();
  await db.exec(BASELINE);
  await db.exec(`insert into auth.users(id) values ('${USER_A}'), ('${USER_B}');`);
  if (seed) await db.exec(seed);

  /*
    seed 가 id 를 직접 적으므로 identity 시퀀스를 그 뒤로 밀어 둔다 —
    그러지 않으면 뒤따르는 insert 가 1 부터 다시 세어 pkey 충돌이 난다.
  */
  await db.exec(`
    alter table public.categories   alter column id restart with 1000;
    alter table public.posts        alter column id restart with 1000;
    alter table public.post_folders alter column id restart with 1000;
    alter table public.banners      alter column id restart with 1000;
  `);

  return db;
}

async function setUid(db, uid) {
  await db.query("update auth.imory_session set uid = $1", [uid]);
}

