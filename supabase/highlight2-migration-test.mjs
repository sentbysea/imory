let passed = 0;
const failures = [];

function check(name, condition, detail) {
  if (condition) { passed += 1; console.log(`  ok   ${name}`); }
  else { failures.push(`${name}${detail ? " — " + detail : ""}`); console.log(`  FAIL ${name}${detail ? " — " + detail : ""}`); }
}

async function expectError(name, fn, codeOrText) {
  try {
    await fn();
    check(name, false, "예외가 나지 않았다");
  } catch (err) {
    const hit =
      String(err.code || "") === codeOrText ||
      String(err.message || "").includes(codeOrText);
    check(name, hit, `code=${err.code} message=${String(err.message).slice(0, 160)}`);
  }
}

