/* =========================================================
   SHARE CARD 자동 라벨 번호 migration 검증 (PGlite — 실제 Postgres)

   기준 문서: IMORY_SHARE_CARD_DESIGN.md §4-3
   대상:      supabase/migrations/20260913180000_add_posts_share_label_seq.sql

   무엇을 확인하는가
   ----------------
   1) [backfill] 기존 공개 글이 컨테이너별로 created_at 오름차순
                 1, 2, 3 ... 을 받는다. 공개가 아닌 글은 받지 않는다.
                 재실행해도 값이 달라지지 않는다.
   2) [assign]   새로 공개되는 글은 그 컨테이너의 **맨 끝** 번호를
                 받는다(max + 1).
   3) [frozen]   ★ 앞 글을 지우거나 비공개로 돌려도 이미 붙은
                 번호는 바뀌지 않는다 — 이 컬럼이 존재하는 이유다.
   4) [move]     다른 폴더/카테고리로 옮기면 그쪽 번호 공간의 맨
                 끝을 새로 받는다(번호가 겹치지 않는다).
   5) [order]    기존 folder/sort_order 트리거가 **먼저** 돌아서
                 확정된 컨테이너를 보고 번호를 매긴다.
   6) [grant]    SELECT 에만 GRANT 가 붙는다(INSERT/UPDATE 없음).

   실행:
     node supabase/share-label-seq-migration-test.mjs

   PGlite 는 supabase/.temp/gallery-validation/node_modules 에 이미
   설치돼 있다(다른 migration 검증 때 받은 것). 이 저장소에는 패키지
   매니저가 없으므로 새로 설치하지 않고 그 경로에서 import 한다.
========================================================== */

import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));

const PGLITE_ENTRY = join(
  HERE, ".temp", "gallery-validation", "node_modules",
  "@electric-sql", "pglite", "dist", "index.js"
);

const { PGlite } = await import(pathToFileURL(PGLITE_ENTRY).href);

const FOLDER_MIGRATION = readFileSync(
  join(HERE, "migrations", "20260908110000_add_posts_folder_id_sort_order.sql"),
  "utf8"
);

const MIGRATION = readFileSync(
  join(HERE, "migrations", "20260913180000_add_posts_share_label_seq.sql"),
  "utf8"
);

let passed = 0;
const failures = [];

function check(name, condition, detail) {
  if (condition) { passed += 1; console.log(`  ok   ${name}`); }
  else { failures.push(`${name}${detail ? " — " + detail : ""}`); console.log(`  FAIL ${name}${detail ? " — " + detail : ""}`); }
}


/* =========================================================
   이 migration 직전까지의 상태

   categories / posts / post_folders 는 프로덕션에서 실측한 컬럼
   구성을 옮겨 적은 것이다(다른 migration 검증과 같은 방식).
   folder_id / sort_order 와 그 트리거는 **저장소의 실제 migration
   파일**을 그대로 실행해서 만든다 — 트리거 실행 순서를 재려면
   진짜 그 트리거가 있어야 한다.
========================================================== */

const BASELINE = `
create schema if not exists auth;

create role anon;
create role authenticated;

create table auth.users (
  id uuid primary key
);

create table public.categories (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  sort_order integer,
  type text not null default 'post'
);

create table public.post_folders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  category_id bigint not null references public.categories(id) on delete cascade,
  parent_id bigint references public.post_folders(id) on delete restrict,
  name text not null,
  depth smallint not null default 1,
  sort_order integer not null default 0
);

create table public.posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  category_id bigint references public.categories(id) on delete set null,
  title text,
  visibility text not null default 'public',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
`;

const OWNER = "11111111-2222-3333-4444-555555555555";
const OTHER = "99999999-8888-7777-6666-555555555555";


async function seed(db) {
  await db.exec(BASELINE);
  await db.exec(FOLDER_MIGRATION);

  await db.exec(`
    insert into auth.users (id) values ('${OWNER}'), ('${OTHER}');

    insert into public.categories (id, user_id, name, sort_order)
    values (1, '${OWNER}', '기록', 1),
           (2, '${OWNER}', 'MUSIC', 2),
           (3, '${OTHER}', '남의 카테고리', 1);

    insert into public.post_folders (id, user_id, category_id, parent_id, name)
    values (7, '${OWNER}', 1, null, '여름');
  `);

  /*
    카테고리 1 root 에 공개 글 셋(오래된 순 a < b < c)과
    비공개 글 하나. 폴더 7 에 공개 글 하나.
  */

  await db.exec(`
    insert into public.posts (id, user_id, category_id, folder_id, title, visibility, created_at)
    values
      (10, '${OWNER}', 1, null,  'a', 'public',  '2026-01-01T00:00:00Z'),
      (11, '${OWNER}', 1, null,  'b', 'public',  '2026-02-01T00:00:00Z'),
      (12, '${OWNER}', 1, null,  'c', 'public',  '2026-03-01T00:00:00Z'),
      (13, '${OWNER}', 1, null,  'x', 'private', '2026-01-15T00:00:00Z'),
      (14, '${OWNER}', 1, 7,     'f', 'public',  '2026-02-15T00:00:00Z'),
      (15, '${OTHER}', 3, null,  'o', 'public',  '2026-01-01T00:00:00Z');
  `);
}


async function seqOf(db, id) {
  const rows = await db.query(
    "select share_label_seq from public.posts where id = $1",
    [id]
  );
  return rows.rows[0] ? rows.rows[0].share_label_seq : undefined;
}


async function run() {
  const db = new PGlite();

  await seed(db);
  await db.exec(MIGRATION);

  console.log("\n[backfill] 기존 공개 글의 최초 계산값");

  check(
    "카테고리 root 의 공개 글이 created_at 오름차순 1·2·3 을 받는다",
    await seqOf(db, 10) === 1 &&
    await seqOf(db, 11) === 2 &&
    await seqOf(db, 12) === 3,
    `${await seqOf(db, 10)} / ${await seqOf(db, 11)} / ${await seqOf(db, 12)}`
  );

  check(
    "공개가 아닌 글은 번호를 받지 않는다",
    await seqOf(db, 13) === null,
    String(await seqOf(db, 13))
  );

  check(
    "폴더 안의 글은 폴더가 자기 번호 공간이다(1번부터)",
    await seqOf(db, 14) === 1,
    String(await seqOf(db, 14))
  );

  check(
    "다른 사용자의 글은 자기 공간에서 1번이다",
    await seqOf(db, 15) === 1,
    String(await seqOf(db, 15))
  );

  /* 재실행 안전 */

  await db.exec(MIGRATION);

  check(
    "★ migration 을 다시 실행해도 이미 붙은 번호가 달라지지 않는다",
    await seqOf(db, 10) === 1 && await seqOf(db, 12) === 3
  );


  console.log("\n[assign] 새로 공개되는 글");

  await db.exec(`
    insert into public.posts (id, user_id, category_id, title, visibility, created_at)
    values (20, '${OWNER}', 1, 'd', 'public', '2026-04-01T00:00:00Z');
  `);

  check(
    "새 공개 글은 컨테이너의 맨 끝 번호를 받는다(max + 1)",
    await seqOf(db, 20) === 4,
    String(await seqOf(db, 20))
  );

  await db.exec(`
    insert into public.posts (id, user_id, category_id, title, visibility, created_at)
    values (21, '${OWNER}', 1, 'e', 'private', '2026-05-01T00:00:00Z');
  `);

  check(
    "비공개로 쓴 글은 아직 번호가 없다",
    await seqOf(db, 21) === null
  );

  await db.exec(`update public.posts set visibility = 'public' where id = 21;`);

  check(
    "★ 공개로 바꾸는 순간 그때의 맨 끝 번호를 받는다",
    await seqOf(db, 21) === 5,
    String(await seqOf(db, 21))
  );

  check(
    "클라이언트가 보낸 값은 무시된다(INSERT)",
    await (async () => {
      await db.exec(`
        insert into public.posts (id, user_id, category_id, title, visibility, share_label_seq)
        values (22, '${OWNER}', 2, 'g', 'public', 999);
      `);
      return await seqOf(db, 22) === 1;
    })(),
    String(await seqOf(db, 22))
  );


  console.log("\n[frozen] 이미 붙은 번호는 바뀌지 않는다");

  await db.exec(`delete from public.posts where id = 10;`);

  check(
    "★ 앞 글을 지워도 뒤 글의 번호가 앞당겨지지 않는다",
    await seqOf(db, 11) === 2 && await seqOf(db, 12) === 3,
    `${await seqOf(db, 11)} / ${await seqOf(db, 12)}`
  );

  await db.exec(`update public.posts set visibility = 'private' where id = 11;`);

  check(
    "★ 비공개로 돌려도 번호를 지우지 않는다(다시 공개하면 같은 번호)",
    await seqOf(db, 11) === 2
  );

  await db.exec(`update public.posts set visibility = 'public' where id = 11;`);

  check(
    "다시 공개해도 같은 번호 그대로다",
    await seqOf(db, 11) === 2
  );

  await db.exec(`update public.posts set title = '제목만 고침' where id = 12;`);

  check(
    "제목만 고쳐도 번호는 그대로다",
    await seqOf(db, 12) === 3
  );


  console.log("\n[move] 컨테이너를 옮기면 그쪽 맨 끝을 새로 받는다");

  await db.exec(`update public.posts set folder_id = 7 where id = 12;`);

  check(
    "★ 폴더로 옮기면 폴더 번호 공간의 맨 끝을 받는다(겹치지 않는다)",
    await seqOf(db, 12) === 2,
    String(await seqOf(db, 12))
  );

  await db.exec(`update public.posts set category_id = 2 where id = 12;`);

  check(
    "★ 카테고리를 바꾸면 folder_id 가 풀린 뒤의 컨테이너에서 번호를 받는다",
    await seqOf(db, 12) === 2 &&
    (await db.query("select folder_id from public.posts where id = 12")).rows[0].folder_id === null,
    `seq=${await seqOf(db, 12)}`
  );


  console.log("\n[order] 트리거 순서");

  const triggers = await db.query(`
    select tgname
      from pg_trigger
     where tgrelid = 'public.posts'::regclass
       and not tgisinternal
     order by tgname
  `);

  const names = triggers.rows.map(r => r.tgname);

  check(
    "★ folder/sort_order 트리거가 share_label_seq 트리거보다 먼저 돈다(이름순)",
    names.indexOf("posts_sync_folder_and_sort_order_trg") >= 0 &&
    names.indexOf("posts_sync_share_label_seq_trg") >
      names.indexOf("posts_sync_folder_and_sort_order_trg"),
    names.join(" < ")
  );


  console.log("\n[grant] SELECT 에만");

  const grants = await db.query(`
    select privilege_type, grantee
      from information_schema.column_privileges
     where table_schema = 'public'
       and table_name = 'posts'
       and column_name = 'share_label_seq'
       and grantee in ('anon', 'authenticated')
     order by grantee, privilege_type
  `);

  const kinds = new Set(grants.rows.map(r => r.privilege_type));

  check(
    "★ anon / authenticated 는 읽기만 할 수 있다",
    kinds.size === 1 && kinds.has("SELECT") &&
    new Set(grants.rows.map(r => r.grantee)).size === 2,
    JSON.stringify(grants.rows)
  );

  await db.close();
}


await run();

console.log(`\n결과: ${passed} PASS / ${failures.length} FAIL`);

if (failures.length) {
  failures.forEach(f => console.log(`  - ${f}`));
  process.exit(1);
}
